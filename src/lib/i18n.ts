const dict: Record<Lang, Record<TKey, string>> = { en, ar }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = dict[lang][key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function useT() {
  const { state } = useStore()
  const lang = state.lang
  const num = (n: number) => n.toLocaleString(lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-US')
  return {
    lang,
    t: (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    pick: (b: Bilingual) => b[lang],
    num,
    // "+50 XP", wrapped in Unicode isolates so it stays in order inside Arabic text.
    xp: (n: number, plus = false) => `\u2066${plus ? '+' : ''}${num(n)} XP\u2069`,
  }
}
